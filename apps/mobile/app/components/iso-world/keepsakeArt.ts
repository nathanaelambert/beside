import type { PixelArt } from "@beside/rewards"

// Approved compact keepsakes on the existing 32 × 32 cell. Offsets place the ink
// within the frame; the world anchor and the existing foot rows do not move.
function registeredArt(
  left: number,
  top: number,
  palette: PixelArt["palette"],
  ink: readonly string[],
): PixelArt {
  const pixels = Array.from({ length: 32 }, (_, y) => {
    const line = ink[y - top] ?? ""
    return line.padStart(left + line.length, ".").padEnd(32, ".")
  })
  return { format: "pixel-art", palette, pixels }
}

